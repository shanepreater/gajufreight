import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { escrowFor } from '../lib/shipment-escrow.js';
import { Platform } from '../lib/platform.js';
import { QuoteRequest } from '../lib/quote-request.js';
import { EVENT_FIELDS, projectEvent, positionalArgs } from '../lib/contract-interface.js';
import { SimChain } from '../lib/sim-chain.js';
import { Demo } from '../lib/demo.js';
import { scenarios } from '../scenarios/index.js';
import { createNarrator } from '../lib/narrator.js';
import { createMemoryLog } from '../lib/audit-log.js';

// The demo models the contracts entrypoint for entrypoint (sophia-contracts skill), so a name
// added or renamed in a contract fails here until the demo follows. The ACI is generated by
// contracts/tools/build.escript and checked current in CI.
const aci = (file) => JSON.parse(readFileSync(new URL(`../../../contracts/interface/${file}.aci.json`, import.meta.url)));

// Known gaps, each to be closed by the issue named. Delete an entry when its gap closes.
const KNOWN = {};

for (const [file, def] of [['shipment-escrow', escrowFor('ak_demo_platform')], ['platform', Platform], ['quote-request', QuoteRequest]]) {
  test(`the ${file} model has the contract's entrypoints, no more and no fewer`, () => {
    const contract = new Set(aci(file).functions.map((f) => f.name).filter((name) => name !== 'init'));
    const demo = new Set([...Object.keys(def.entrypoints), ...Object.keys(def.views)]);
    const diff = {
      onlyInContract: [...contract].filter((n) => !demo.has(n)).sort(),
      onlyInDemo: [...demo].filter((n) => !contract.has(n)).sort(),
    };
    assert.deepEqual(diff, KNOWN[file] ?? { onlyInContract: [], onlyInDemo: [] });
  });
}

// The model's events carry the contract's names, in its field order (EVENT_FIELDS).
for (const [contract, file] of [['ShipmentEscrow', 'shipment-escrow'], ['Platform', 'platform'], ['QuoteRequest', 'quote-request']]) {
  test(`${contract}: the event table matches the contract's events, name for name and field for field`, () => {
    const variants = Object.fromEntries(aci(file).event.variant.map((v) => Object.entries(v)[0]).map(([name, fields]) => [name, fields.length]));
    const table = Object.fromEntries(Object.entries(EVENT_FIELDS[contract]).map(([name, fields]) => [name, fields.length]));
    assert.deepEqual(table, variants);
  });
}

test('every event the customer scenarios emit is one the contracts emit', async () => {
  const unknown = new Set();
  for (const scenario of scenarios) {
    const demo = new Demo({ chain: new SimChain(), narrator: createNarrator({ silent: true }), audit: createMemoryLog() });
    await scenario.run(demo);
    for (const e of demo.chain.events()) {
      try {
        projectEvent(demo.chain.contractName(e.contract), e);
      } catch {
        unknown.add(`${demo.chain.contractName(e.contract)}.${e.type}`);
      }
    }
  }
  assert.deepEqual([...unknown], []);
});

describe('arguments in the contract\'s order', () => {
  test('camelCase names map to the contract\'s snake_case ones, in its order', () => {
    assert.deepEqual(positionalArgs('ShipmentEscrow', 'confirm_delivery', { codeChecked: true, evidence: 'e' }), ['e', true]);
    assert.deepEqual(positionalArgs('ShipmentEscrow', 'vote', { payCarrierPct: 50n }), [50n]);
  });
  test('aliases cover names the demo spells differently', () => {
    assert.deepEqual(positionalArgs('ShipmentEscrow', 'add_attestor', { attestor: 'ak_demo_x' }), ['ak_demo_x']);
    assert.deepEqual(positionalArgs('QuoteRequest', 'accept', { invitee: 'i', terms: 'h' }), ['i', 'h']);
  });
  test('a quote sends only the quote_terms record, always with its attestors', () => {
    const [terms] = positionalArgs('QuoteRequest', 'quote', { terms: { price: 1n, schedule: [], deadline: 2, panel: ['ak_demo_p'] }, validUntil: 9 });
    assert.deepEqual(terms, { attestors: [], replace: null, price: 1n, schedule: [], deadline: 2 });
  });
  test('an option the demo leaves out is None (null)', () => {
    assert.deepEqual(positionalArgs('Platform', 'book', { quote: 'q', manifest: 'm' }), ['q', 'm', null]);
  });
  test('a missing argument, or a function the contract lacks, is drift and throws', () => {
    assert.throws(() => positionalArgs('ShipmentEscrow', 'vote', {}), /passes no 'payCarrierPct'/);
    assert.throws(() => positionalArgs('Platform', 'add_leg', {}), /not in the contract's interface/);
  });
});
